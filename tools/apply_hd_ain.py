# -*- coding: utf-8 -*-
"""Apply the HD immediate patch to any Rance7.ain variant.

Sites are located semantically: function name + local instruction context
(see tools/hd_sites.json generated by ain_export_sites.py). This works on
vanilla, JP-patched and NationalExpansion-patched AINs alike, as long as the
surrounding instructions still match.

Usage:
    python tools/apply_hd_ain.py <input.ain> <output.ain> [--dry-run]
"""
import bisect
import json
import os
import re
import struct
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ain_hd_patch import _mt_stream  # noqa: E402

ALICE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "alice.exe")
SITES_JSON = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "hd_sites.json")

VOLATILE_OPS = {
    "S_PUSH", "MSG", "CALLFUNC", "CALLSYS", "CALLMETHOD", "CALLHLL",
    "JUMP", "IFZ", "IFNZ", "SWITCH", "EOF", "FUNC", "ENDFUNC",
    "CALLONJUMP", "SJUMP", "CALLFUNCREF", "DELEGATE",
}
CTX = 3


def decrypt(data):
    ks = _mt_stream(0x5D3E3, len(data))
    return bytearray(b ^ k for b, k in zip(data, ks))


def is_encrypted(data):
    return data[:4] != b"VERS"


def parse_sections(dec):
    secs = {}
    pos = 0
    while pos + 8 <= len(dec):
        tag = dec[pos:pos + 4]
        size = struct.unpack_from("<I", dec, pos + 4)[0]
        if not all(32 <= b < 127 for b in tag):
            break
        secs[tag.decode("ascii")] = (pos + 8, size)
        pos += 8 + size
        if pos % 4:
            pos += 4 - pos % 4
    return secs


def parse_raw_dump(path):
    """Same parser as ain_export_sites: returns list of function dicts."""
    funcs = []
    name = None
    cur = None
    addr_re = re.compile(r"0x([0-9a-fA-F]+):")
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"; (\S+)", line)
        if m:
            if not any(line.startswith(p) for p in
                       ("; ARG", "; VAR", "; RETURN")):
                if cur is not None:
                    funcs.append(cur)
                    cur = None
                name = m.group(1)
            continue
        if line.startswith("FUNC "):
            cur = {"name": name, "no": int(line.split()[1]), "lo": None,
                   "instrs": []}
            continue
        a = addr_re.match(line)
        if not a:
            continue
        addr = int(a.group(1), 16)
        body = line[a.end():].strip()
        if "ENDFUNC" in body:
            if cur is not None:
                funcs.append(cur)
                cur = None
            continue
        if not body:
            if cur is not None:
                funcs.append(cur)
                cur = None
            continue
        parts = body.split(None, 1)
        op = parts[0]
        ops = parts[1] if len(parts) > 1 else ""
        if cur is not None:
            if cur["lo"] is None:
                cur["lo"] = addr
            cur["instrs"].append((addr, op, ops))
    if cur is not None:
        funcs.append(cur)
    return funcs


def norm_tok(tok):
    """Normalize one operand token: numbers -> int, else raw string."""
    try:
        return ("num", int(tok, 0))
    except ValueError:
        return ("str", tok)


def norm_ops_tokens(op, ops):
    if op in VOLATILE_OPS:
        return None  # fully masked
    return [norm_tok(t) for t in ops.split()]


def site_signature(site):
    """(target op, target normalized tokens with operand idx wildcarded,
        ctx signature list)"""
    toks = norm_ops_tokens(site["op"],
                           site["ctx"][CTX][2] if len(site["ctx"]) > CTX else "")
    # site's own instruction is at ctx index CTX when available
    return None  # built differently below


def instr_matches(instr, want_op, want_toks, skip_tok=None):
    a, op, ops = instr
    if op != want_op:
        return False
    if want_toks is None:
        return True
    got = norm_ops_tokens(op, ops)
    if got is None:
        return False  # op is volatile in target but wasn't in jp
    if len(got) != len(want_toks):
        return False
    for i, (g, w) in enumerate(zip(got, want_toks)):
        if i == skip_tok:
            continue
        if w is None:
            continue
        if g != w:
            return False
    return True


def build_site(site):
    """Decompose a hd_sites entry into matching primitives."""
    op = site["op"]
    delta = site["delta"]
    tok_idx = (delta - 2) // 4
    ctx = site["ctx"]  # list of [addr, op, ops] around site
    # locate site's own ctx entry (the one whose addr == site addr)
    ci = next((i for i, c in enumerate(ctx) if c[0] == site["addr"]), None)
    self_toks = norm_ops_tokens(op, ctx[ci][2]) if ci is not None else None
    return {"op": op, "delta": delta, "tok_idx": tok_idx,
            "self_toks": self_toks, "ctx": ctx, "ci": ci,
            "old": site["old"], "new": site["new"], "func": site["func"],
            "idx": site["idx"], "rank": site.get("rank"),
            "n_match": site.get("n_match"), "addr": site["addr"]}


def ctx_match_at(ins, j, ctx, ci):
    """Check whether the context window around ins[j] matches the recorded
    signature. ctx entries are [addr, op, ops]; offsets are relative to ci."""
    for k, centry in enumerate(ctx):
        rel = k - ci
        jj = j + rel
        if jj < 0 or jj >= len(ins):
            return False
        _, op, ops = centry
        a2, op2, ops2 = ins[jj]
        if op2 != op:
            return False
        wt = norm_ops_tokens(op, ops)
        gt = norm_ops_tokens(op2, ops2)
        if wt is None:
            continue
        if gt is None or gt != wt:
            return False
    return True


def main():
    src, dst = sys.argv[1], sys.argv[2]
    dry = "--dry-run" in sys.argv

    data = open(src, "rb").read()
    enc = is_encrypted(data)
    dec = decrypt(data) if enc else bytearray(data)
    code_off, code_size = parse_sections(dec)["CODE"]

    fd, dump_path = tempfile.mkstemp(suffix=".jam")
    os.close(fd)
    try:
        subprocess.run([ALICE, "ain", "dump", "-C", "-o", dump_path, src],
                       check=True)
        funcs = parse_raw_dump(dump_path)
    finally:
        os.unlink(dump_path)

    by_name = {}
    for f in funcs:
        by_name.setdefault(f["name"], []).append(f)

    sites = json.load(open(SITES_JSON, encoding="utf-8"))["sites"]

    # group sites by (func, signature) to handle repeated patterns by order
    stats = {"ok": 0, "missing_func": 0, "no_match": 0, "ambiguous": 0,
             "relaxed": 0}
    problems = []

    # For order-based resolution, compute per func+sig signature groups.
    groups = {}
    for s in sites:
        b = build_site(s)
        key = (s["func"], s["op"],
               tuple(tuple(t) if t else None for t in
                     (b["self_toks"] or [])),
               s["delta"],
               tuple((c[1], c[2]) for c in s["ctx"]))
        groups.setdefault(key, []).append(b)

    writes = []  # (file_offset, old, new, site)

    for key, grp in groups.items():
        # all sites in grp share the same signature; in the jp ain they
        # correspond to occurrences in instruction order.
        fname = key[0]
        targets = by_name.get(fname, [])
        if not targets:
            stats["missing_func"] += len(grp)
            problems.append(("missing_func", fname, len(grp)))
            continue
        grp_sorted = sorted(grp, key=lambda g: g["idx"])
        b0 = grp_sorted[0]
        for fcopy in targets:
            ins = fcopy["instrs"]
            # find all positions matching the signature
            matches = []
            for j in range(len(ins)):
                if not instr_matches(ins[j], b0["op"], b0["self_toks"],
                                     skip_tok=b0["tok_idx"]):
                    continue
                if not ctx_match_at(ins, j, b0["ctx"], b0["ci"]):
                    continue
                matches.append(j)
            if len(matches) != len(grp_sorted):
                if len(matches) == 0:
                    # Relaxed fallback: the function body was rewritten by
                    # another mod (e.g. NationalExpansion override). Patch
                    # every operand slot equal to `old` inside this copy.
                    relaxed = 0
                    for b in grp_sorted:
                        for j2 in range(len(ins)):
                            a2, op2, _ = ins[j2]
                            pos = a2 + 2
                            while pos < (ins[j2 + 1][0] if j2 + 1 < len(ins)
                                         else a2 + 64):
                                file_off = code_off + pos
                                if struct.unpack_from("<i", dec,
                                                      file_off)[0] \
                                        == b["old"]:
                                    writes.append((file_off, b["old"],
                                                   b["new"], fname, pos))
                                    relaxed += 1
                                pos += 4
                    stats["relaxed"] += relaxed
                    problems.append(("relaxed", fname,
                                     [b["old"] for b in grp_sorted],
                                     relaxed))
                    continue
                if len(matches) > len(grp_sorted):
                    # Extra matches in target: fall back to jp-side rank
                    pair = []
                    ok = True
                    for b in grp_sorted:
                        r = b.get("rank")
                        if r is None or r >= len(matches):
                            ok = False
                            break
                        pair.append((b, matches[r]))
                    if ok:
                        for b, j in pair:
                            addr = ins[j][0]
                            file_off = code_off + addr + b["delta"]
                            cur = struct.unpack_from("<i", dec, file_off)[0]
                            if cur == b["old"]:
                                writes.append((file_off, b["old"],
                                               b["new"], fname, addr))
                                stats["ok"] += 1
                            elif cur != b["new"]:
                                stats["ambiguous"] += 1
                                problems.append(("value_mismatch", fname,
                                                 hex(addr), b["old"], cur))
                        continue
                    stats["ambiguous"] += len(grp_sorted)
                    problems.append(("count_mismatch", fname,
                                     len(grp_sorted), len(matches)))
                    continue
                stats["ambiguous"] += len(grp_sorted)
                problems.append(("count_mismatch", fname,
                                 len(grp_sorted), len(matches)))
                continue
            for b, j in zip(grp_sorted, matches):
                addr = ins[j][0]
                file_off = code_off + addr + b["delta"]
                cur = struct.unpack_from("<i", dec, file_off)[0]
                if cur == b["new"]:
                    continue  # already patched
                if cur != b["old"]:
                    stats["ambiguous"] += 1
                    problems.append(("value_mismatch", fname,
                                     hex(addr), b["old"], cur))
                    continue
                writes.append((file_off, b["old"], b["new"], fname, addr))
                stats["ok"] += 1

    print("resolved:", stats["ok"], " missing_func:", stats["missing_func"],
          " no_match:", stats["no_match"], " ambiguous:", stats["ambiguous"],
          " relaxed:", stats["relaxed"])
    for p in problems[:40]:
        print("  !", p)
    if len(problems) > 40:
        print("   ... and", len(problems) - 40, "more")

    if dry:
        return

    seen = {}
    for off, old, new, fname, addr in writes:
        if off in seen and seen[off] != new:
            raise SystemExit(
                "conflicting writes @0x%x (%s): %d vs %d"
                % (off, fname, seen[off], new))
        seen[off] = new
        struct.pack_into("<i", dec, off, new)
    if enc:
        ks = _mt_stream(0x5D3E3, len(dec))
        out = bytes(b ^ k for b, k in zip(dec, ks))
    else:
        out = bytes(dec)
    open(dst, "wb").write(out)
    print("wrote", dst, len(out), "bytes;", len(writes), "sites patched")


if __name__ == "__main__":
    main()
